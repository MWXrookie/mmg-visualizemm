/** Sanity 检查清单（实现/算完后使用） */
export const SANITY_CHECK =
  '【Sanity 检查】每个小问算完后，带用户过一遍：\n' +
  '1. 量纲与守恒：相同量纲才能相加；率×时间得数量；成分总和≈100%？\n' +
  '2. 边界测试：零输入/极端值/单对象特例是否合理？\n' +
  '3. 数量级：结果和常识差 10 倍以上？先查单位/百分数混淆（20% 是 0.2 不是 20）。\n' +
  '4. 数值：NaN/Inf？负值？约束残差？随机种子可重复？\n' +
  '5. 跨问一致性：变量名/单位/数据版本统一？后问引用前问结果是否最新？\n' +
  '对不合理结果直接质疑（"这个结果我不信，可能原因有……我们查"），而不是接受任何输出。'

