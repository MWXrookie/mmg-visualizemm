/** Sanity 检查清单（实现/算完后使用） */
export const SANITY_CHECK =
  '【Sanity 检查】每个小问算完后，带用户过一遍：\n' +
  '1. 量纲与守恒：相同量纲才能相加；率×时间得数量；成分总和≈100%？具体单位（尤其元、人民币、CNY）先回查题干、附件或用户确认；来源未给出就标明单位未指定，不把推测单位写进表头、图轴、代码注释或结论。来源明确时照原文使用。\n' +
  '2. 边界测试：零输入/极端值/单对象特例是否合理？\n' +
  '3. 数量级：结果和常识差 10 倍以上？先查单位/百分数混淆（20% 是 0.2 不是 20）。\n' +
  '4. 数值：NaN/Inf？负值？约束残差？随机种子可重复？先按指标定义区分预期未定义与计算故障，例如无概率分数的多数类基线不计算 AUC；仅对本应有定义的非有限值报警，不能把整张表的 NaN 一概说成模型退化。\n' +
  '5. 跨问一致性：变量名/单位/数据版本统一？后问引用前问结果是否最新？\n' +
  '6. 分类结果：先从实际标签逐类计数并计算占比；最高计数并列时明确称“并列”，不硬指定多数类或少数类，也不把接近均衡写成严重不平衡。固定预测同一类别的基线，才与测试集该类别占比同口径比较；若每折从训练集重新选多数类，须逐折记录所选类别和预测，再汇总基线准确率，不得直接拿全体类别占比当作该基线的期望值。按组留一时，折内多数类可能恰与留出组相反，差异本身不证明划分异常。最终 print 的类别名称、占比、偏斜程度和警告须由实际计数、折内规则及明确条件分支在运行时生成；无法确认时打印“待核查”，且与表格、混淆矩阵和指标一致。\n' +
  '7. 预测区间：若标称 90%/95% 等覆盖水平，说明区间构造、误差与参数假设；有时间留出数据时按同口径逐点核对命中数/总数，不用拟合内残差冒充独立覆盖验证。样本很少时只报告观察结果与不确定性，不因少数点未命中就断言长期覆盖率；没有校准证据时不得称“已校准”。分别说明验证阶段的训练边界与为未来预测进行的全样本重估。\n' +
  '对不合理结果直接质疑（"这个结果我不信，可能原因有……我们查"），而不是接受任何输出。'

